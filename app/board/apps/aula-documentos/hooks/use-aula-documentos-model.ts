import { useEffect, useRef } from "react";
import type { Editor } from "@tiptap/core";
import type { StoreRole } from "../../types";
import { useDialogFocus } from "../../../shared/use-dialog-focus";
import { useAulaSession } from "./use-aula-session";
import { useAulaDocumentSuite } from "./use-aula-document-suite";
import { useAulaSearch } from "./use-aula-search";
import { useAulaNavigation } from "./use-aula-navigation";
import { useAulaView } from "./use-aula-view";
import { useAulaSlideStructure } from "./use-aula-slide-structure";
import { useAulaComments } from "./use-aula-comments";
import { useAulaVersions } from "./use-aula-versions";
import { useAulaSuiteController } from "./use-aula-suite-controller";
import { useAulaPersistence } from "./use-aula-persistence";
import { useAulaImages } from "./use-aula-images";
import { useAulaLink } from "./use-aula-link";
import { useAulaMigration } from "./use-aula-migration";
import { useAulaPresentation } from "./use-aula-presentation";
import { useAulaExports } from "./use-aula-exports";
import { useAulaRecovery } from "./use-aula-recovery";
import { useAulaCopies } from "./use-aula-copies";
import { useAulaNewDocument } from "./use-aula-new-document";
import { useAulaImport } from "./use-aula-import";
import { useAulaToolbarModel } from "./use-aula-toolbar-model";

/**
 * Compone todos los flujos de Aula Documentos en un único modelo de vista.
 * @param props - Proyecto activo y rol.
 * @returns Estado y acciones de la app.
 */
export function useAulaDocumentosModel({ projectId, role }: { projectId: string; role: StoreRole }) {
  const editorRef = useRef<Editor | null>(null);
  const insertImageRef = useRef<(files: File[], position?: number) => Promise<void>>(async () => {});
  const readOnly = role === "guest";

  const {
    title,
    setTitle,
    dirty,
    setDirty,
    saving,
    setSaving,
    saveFailed,
    setSaveFailed,
    lastSavedAt,
    setLastSavedAt,
    editVersion,
    status,
    setStatus,
    wordCount,
    diagramCount,
    actionsOpen,
    setActionsOpen,
    presentationTheme,
    setPresentationTheme,
    presentationNotes,
    setPresentationNotes,
    presentationPage,
    setPresentationPage,
    titleRef,
    editVersionRef,
    savingRef,
    mountedRef,
    documentVersionRef,
    actionsRef,
    actionsToggleRef,
    editor,
    toolbar,
    markChanged,
    applyDocument,
    currentDocument,
    updateTitle,
  } = useAulaSession({
    projectId,
    readOnly,
    editorRef,
    insertImageRef,
  });
  const navigation = useAulaNavigation({ editor });
  const {
    imageUploading,
    openImagePicker,
    insertImageFiles,
    insertMermaid,
    insertSlideBreak,
  } = useAulaImages({
    editorRef,
    readOnly,
    projectId,
    setStatus,
  });
  useEffect(() => {
    insertImageRef.current = insertImageFiles;
  }, [insertImageFiles]);

  const {
    linkOpen,
    setLinkOpen,
    linkUrl,
    setLinkUrl,
    linkError,
    setLinkError,
    openLinkPanel,
    applyLink,
    removeLink,
  } = useAulaLink({ editor, readOnly, setStatus });

  const {
    preparingPresentation,
    presentation,
    exportingPresentation,
    slidePreview,
    setSlidePreview,
    markdownSourceOpen,
    setMarkdownSourceOpen,
    markdownSourceDraft,
    setMarkdownSourceDraft,
    markdownSourceError,
    slidePreviewRef,
    markdownSourceRef,
    startPresentation,
    openSlidePreview,
    openMarkdownSource,
    applyMarkdownSource,
    changePresentationTheme,
    changePresentationPage,
    changeSlideNote,
    exportPresentation,
    printingPresentation,
    printPresentation,
    closePresentation,
  } = useAulaPresentation({
    currentDocument,
    title,
    presentationTheme,
    presentationNotes,
    presentationPage,
    setPresentationTheme,
    setPresentationNotes,
    setPresentationPage,
    applyDocument,
    markChanged,
    setStatus,
  });
  useDialogFocus(Boolean(slidePreview), () => setSlidePreview(null), slidePreviewRef);
  useDialogFocus(markdownSourceOpen, () => setMarkdownSourceOpen(false), markdownSourceRef);

  const suite = useAulaDocumentSuite(projectId);
  const comments = useAulaComments({ projectId, documentId: suite.documentId, editor, role, setStatus });
  const { exporting, printing, exportingOffice, includeCommentsInExport, setIncludeCommentsInExport, exportHtml, printDocument, exportMarkdown, exportOffice } = useAulaExports({ currentDocument, presentationNotes, presentationPage, comments: comments.comments, setStatus });
  const versions = useAulaVersions({ projectId, documentId: suite.documentId, role, documentVersionRef, setLastSavedAt, applyDocument, setStatus });
  const search = useAulaSearch({ editor, readOnly, setStatus, documentId: suite.documentId });
  const view = useAulaView({ editor, searchOpen: search.searchOpen });
  const slideStructure = useAulaSlideStructure({ editor, documentId: suite.documentId, readOnly, presentationNotes, setPresentationNotes, markChanged, setStatus });

  const {
    recoveryOpen,
    recoveryCopies,
    recoveryCount,
    recoveryRestoreId,
    setRecoveryRestoreId,
    recoveryNotice,
    setRecoveryNotice,
    recoveryRef,
    storeRecoveryCopy,
    openRecoveryCopies,
    closeRecoveryCopies,
    downloadRecoveryCopy,
    restoreRecoveryCopy,
  } = useAulaRecovery({
    projectId,
    documentId: suite.documentId,
    currentDocument,
    applyDocument,
    markChanged,
    setStatus,
    documentVersionRef,
  });
  useDialogFocus(recoveryOpen, closeRecoveryCopies, recoveryRef);

  const {
    loading,
    error,
    closePromptOpen,
    setClosePromptOpen,
    invalidDocument,
    invalidDocumentRef,
    invalidResetConfirm,
    setInvalidResetConfirm,
    saveConflict,
    setSaveConflict,
    conflictNotice,
    setConflictNotice,
    closePromptRef,
    conflictRef,
    applyLoadedState,
    loadSavedDocument,
    downloadInvalidDocument,
    resetInvalidDocument,
    closeWithoutSaving,
    saveAndClose,
    saveCurrent,
    downloadConflictCopy,
    reloadServerVersion,
    keepMineVersion,
  } = useAulaPersistence({
    projectId,
    documentId: suite.documentId,
    readOnly,
    title,
    setTitle,
    dirty,
    setDirty,
    saving,
    setSaving,
    saveFailed,
    setSaveFailed,
    setLastSavedAt,
    editVersion,
    setStatus,
    editor,
    currentDocument,
    applyDocument,
    markChanged,
    storeRecoveryCopy,
    documentVersionRef,
    editVersionRef,
    savingRef,
    mountedRef,
  });
  const {
    migrationOpen,
    setMigrationOpen,
    migrationStatus,
    migrationLoading,
    migrationError,
    migrationNotice,
    migrationRef,
    openMigration,
    runMigration,
  } = useAulaMigration({
    projectId,
    dirty,
    savingRef,
    applyLoadedState,
    applyDocument,
    setLastSavedAt,
    setDirty,
    setStatus,
  });
  useDialogFocus(migrationOpen, () => setMigrationOpen(false), migrationRef);

  const {
    copiesOpen,
    copies,
    copiesLoading,
    copiesError,
    copyNotice,
    copySaving,
    copyDeleteId,
    setCopyDeleteId,
    copyImport,
    copyImportOpen,
    copyImportConfirm,
    setCopyImportConfirm,
    copyImportBusy,
    copyImportError,
    copiesRef,
    copyImportRef,
    openCopies,
    closeCopies,
    saveCurrentCopy,
    downloadLocalCopy,
    downloadStoredCopy,
    removeStoredCopy,
    openCopyImportPicker,
    prepareCopyImport,
    closeCopyImport,
    applyCopyImport,
  } = useAulaCopies({
    projectId,
    documentId: suite.documentId,
    readOnly,
    currentDocument,
    storeRecoveryCopy,
    applyDocument,
    markChanged,
    setStatus,
  });
  useDialogFocus(copiesOpen, closeCopies, copiesRef);
  useDialogFocus(copyImportOpen, closeCopyImport, copyImportRef);

  const {
    newDocumentOpen,
    newDocumentPreview,
    setNewDocumentPreview,
    newDocumentError,
    newDocumentRef,
    openNewDocument,
    closeNewDocument,
    selectNewDocumentTemplate,
    applyNewDocument,
  } = useAulaNewDocument({
    storeRecoveryCopy,
    applyDocument,
    markChanged,
    titleRef,
    editorRef,
  });
  useDialogFocus(newDocumentOpen, closeNewDocument, newDocumentRef, actionsToggleRef);

  const {
    importOpen,
    importPreview,
    setImportPreview,
    importOfficeSource,
    officeOpenSource,
    officePreviewOpen,
    setOfficePreviewOpen,
    officePreviewTitle,
    setOfficePreviewTitle,
    importLoading,
    importError,
    setImportError,
    importConfirm,
    setImportConfirm,
    pasteText,
    setPasteText,
    importFile,
    importPasted,
    importRef,
    officePreviewRef,
    officeOpenInputRef,
    openImport,
    closeImport,
    closeOfficePreview,
    openOfficeViewer,
    applyImport,
  } = useAulaImport({
    currentDocument,
    storeRecoveryCopy,
    applyDocument,
    markChanged,
  });
  useDialogFocus(importOpen, closeImport, importRef, actionsToggleRef);
  useDialogFocus(officePreviewOpen, closeOfficePreview, officePreviewRef);

  const suiteActions = useAulaSuiteController({
    suite,
    dirty,
    saveCurrent,
    setTitle,
    storeRecoveryCopy,
  });

  const toolbarModel = useAulaToolbarModel({
    loading,
    error,
    saving,
    saveFailed,
    status,
    dirty,
    readOnly,
    saveConflict,
    lastSavedAt,
    wordCount,
    diagramCount,
    editor,
    toolbar,
    invalidDocument,
    importPreview,
    newDocumentPreview,
    presentation,
    preparingPresentation,
    exporting,
    printing,
    exportingPresentation,
    exportingOffice,
    imageUploading,
    officeOpenInputRef,
    saveCurrent,
    exportHtml,
    printDocument,
    exportMarkdown,
    exportOffice,
    startPresentation,
    exportPresentation,
    openNewDocument,
    openCopies,
    openImport,
    openCopyImportPicker,
    openMigration,
    openImagePicker,
    insertMermaid,
    insertSlideBreak,
    openLinkPanel,
  });

  return {
    readOnly,
    editor,
    toolbar,
    title,
    dirty,
    saving,
    saveFailed,
    actionsOpen,
    setActionsOpen,
    presentationTheme,
    presentationNotes,
    presentationPage,
    titleRef,
    actionsRef,
    actionsToggleRef,
    updateTitle,
    insertImageFiles,
    linkOpen,
    setLinkOpen,
    linkUrl,
    setLinkUrl,
    linkError,
    setLinkError,
    applyLink,
    removeLink,
    migrationOpen,
    setMigrationOpen,
    migrationStatus,
    migrationLoading,
    migrationError,
    migrationNotice,
    migrationRef,
    runMigration,
    preparingPresentation,
    presentation,
    slidePreview,
    setSlidePreview,
    markdownSourceOpen,
    setMarkdownSourceOpen,
    markdownSourceDraft,
    setMarkdownSourceDraft,
    markdownSourceError,
    slidePreviewRef,
    markdownSourceRef,
    openSlidePreview,
    openMarkdownSource,
    applyMarkdownSource,
    changePresentationTheme,
    changePresentationPage,
    changeSlideNote,
    printingPresentation,
    printPresentation,
    closePresentation,
    includeCommentsInExport,
    setIncludeCommentsInExport,
    recoveryOpen,
    recoveryCopies,
    recoveryCount,
    recoveryRestoreId,
    setRecoveryRestoreId,
    recoveryNotice,
    setRecoveryNotice,
    recoveryRef,
    openRecoveryCopies,
    closeRecoveryCopies,
    downloadRecoveryCopy,
    restoreRecoveryCopy,
    loading,
    closePromptOpen,
    setClosePromptOpen,
    invalidDocument,
    invalidDocumentRef,
    invalidResetConfirm,
    setInvalidResetConfirm,
    saveConflict,
    setSaveConflict,
    conflictNotice,
    setConflictNotice,
    closePromptRef,
    conflictRef,
    loadSavedDocument,
    downloadInvalidDocument,
    resetInvalidDocument,
    closeWithoutSaving,
    saveAndClose,
    saveCurrent,
    downloadConflictCopy,
    reloadServerVersion,
    keepMineVersion,
    copiesOpen,
    copies,
    copiesLoading,
    copiesError,
    copyNotice,
    copySaving,
    copyDeleteId,
    setCopyDeleteId,
    copyImport,
    copyImportOpen,
    copyImportConfirm,
    setCopyImportConfirm,
    copyImportBusy,
    copyImportError,
    copiesRef,
    copyImportRef,
    closeCopies,
    saveCurrentCopy,
    downloadLocalCopy,
    downloadStoredCopy,
    removeStoredCopy,
    prepareCopyImport,
    closeCopyImport,
    applyCopyImport,
    newDocumentOpen,
    newDocumentPreview,
    setNewDocumentPreview,
    newDocumentError,
    newDocumentRef,
    closeNewDocument,
    selectNewDocumentTemplate,
    applyNewDocument,
    importOpen,
    importPreview,
    setImportPreview,
    importOfficeSource,
    officeOpenSource,
    officePreviewOpen,
    setOfficePreviewOpen,
    officePreviewTitle,
    setOfficePreviewTitle,
    importLoading,
    importError,
    setImportError,
    importConfirm,
    setImportConfirm,
    pasteText,
    setPasteText,
    importFile,
    importPasted,
    importRef,
    officePreviewRef,
    officeOpenInputRef,
    closeImport,
    closeOfficePreview,
    openOfficeViewer,
    applyImport,
    suite: suite.suite,
    suiteDocumentId: suite.documentId,
    suiteLoading: suite.loading,
    suiteInitializing: suite.initializing,
    suiteError: suite.error,
    suiteRetry: suite.retry,
    ...suiteActions,
    ...search,
    ...view,
    ...navigation,
    ...slideStructure,
    ...comments,
    ...versions,
    ...toolbarModel,
  };
}
